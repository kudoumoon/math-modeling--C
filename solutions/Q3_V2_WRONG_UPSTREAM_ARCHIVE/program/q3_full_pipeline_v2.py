class ForecastCache:
    def __init__(
        self,
        dataset: core.Dataset,
        book: q3p1.ForecastBook,
        q2_library: Dict[Tuple[str, str], Dict[int, core.Forecast]],
    ) -> None:
        self.dataset = dataset
        self.book = book
        self.q2_library = q2_library
        self.cache: Dict[Tuple[int, int, bool], q3p1.ReleaseForecast] = {}

    def get(self, day: int, release: int, correction: bool) -> q3p1.ReleaseForecast:
        key = (day, release, correction)
        if key not in self.cache:
            self.cache[key] = q3p1.build_release_forecast(
                self.dataset,
                self.book,
                self.q2_library,
                day,
                release,
                use_load_correction=correction,
            )
        return self.cache[key]


class CurveCache:
    def __init__(
        self,
        dataset: core.Dataset,
        q2_library: Dict[Tuple[str, str], Dict[int, core.Forecast]],
    ) -> None:
        self.dataset = dataset
        self.q2_library = q2_library
        self.cache: Dict[Tuple[int, float], Tuple[np.ndarray, np.ndarray]] = {}

    def get(self, day: int, alpha: float) -> Tuple[np.ndarray, np.ndarray]:
        key = (day, float(alpha))
        if key not in self.cache:
            cfg = q2full.StrategyConfig(
                "Q3_terminal_value",
                q3p1.LOAD_MODEL,
                q3p1.PV_MODEL_FOR_Q2_VALUE,
                float(alpha),
                "pwl",
            )
            curve = q2full.next_day_value_curve(
                self.dataset, day, cfg, self.q2_library
            )
            if not curve["monotone"] or not curve["convex"]:
                raise AssertionError(f"{self.dataset.dates[day].date()}价值曲线形状失败")
            self.cache[key] = (
                np.asarray(curve["grid"], dtype=float),
                np.asarray(curve["values"], dtype=float),
            )
        grid, values = self.cache[key]
        return grid.copy(), values.copy()


def residual_pools(
    dataset: core.Dataset,
    cache: ForecastCache,
    day: int,
    release: int,
    steps: np.ndarray,
    correction: bool,
    risk_days: int,
    gate_days: int,
) -> Tuple[np.ndarray, np.ndarray, List[int], List[int]]:
    issue = dataset.dates[day] + pd.Timedelta(hours=release)
    candidates: List[int] = []
    lookback = risk_days + gate_days + 2
    for old in range(max(0, day - lookback), day):
        latest_end = dataset.interval_starts(old)[int(np.max(steps))] + pd.Timedelta(minutes=10)
        if latest_end <= issue:
            candidates.append(old)
    residuals = []
    for old in candidates:
        old_forecast = cache.get(old, release, correction)
        positions = np.searchsorted(old_forecast.steps, steps)
        prediction = old_forecast.net_kwh[positions]
        actual = dataset.load_kwh[old, steps] - dataset.pv_kwh[old, steps]
        residuals.append(actual - prediction)
    if not residuals:
        width = len(steps)
        return np.zeros((0, width)), np.zeros((0, width)), [], []
    matrix = np.vstack(residuals)
    nr = min(risk_days, len(matrix))
    risk = matrix[-nr:]
    gate_end = len(matrix) - nr
    gate_start = max(0, gate_end - gate_days)
    return (
        risk,
        matrix[gate_start:gate_end],
        candidates[-nr:],
        candidates[gate_start:gate_end],
    )


def solve_adjustment(
    q0: np.ndarray,
    forecast: q3p1.ReleaseForecast,
    margin: np.ndarray,
    start_soc: float,
    block: Tuple[int, int],
    price: np.ndarray,
    settlement: str,
    terminal_curve: Optional[Tuple[np.ndarray, np.ndarray]],
    hard_anchor: Optional[float] = None,
    perfect_net: Optional[np.ndarray] = None,
) -> Dict[str, object]:
    steps = forecast.steps
    n = len(steps)
    ou, or_, oc, od, oh, ow = 0, n, 2 * n, 3 * n, 4 * n, 5 * n
    oe = 6 * n
    use_pwl = terminal_curve is not None
    oz = oe + n + 1
    nvar = oz + 1 if use_pwl else oe + n + 1
    obj = np.zeros(nvar)
    p = price[steps]
    obj[ou:ou + n] = 1.5 * p
    obj[or_:or_ + n] = -0.5 * p if settlement == "B" else 0.5 * p
    obj[oc:oc + n] = core.EPS_THROUGHPUT
    obj[od:od + n] = core.EPS_THROUGHPUT
    obj[oh:oh + n] = 5.0 * p
    if use_pwl:
        obj[oz] = 1.0

    aeq = sparse.lil_matrix((2 * n, nvar))
    beq = np.zeros(2 * n)
    risk_net = perfect_net if perfect_net is not None else forecast.net_kwh + margin
    for k, step in enumerate(steps):
        aeq[k, ou + k] = 1.0
        aeq[k, or_ + k] = -1.0
        aeq[k, oc + k] = -1.0
        aeq[k, od + k] = 1.0
        aeq[k, oh + k] = 1.0
        aeq[k, ow + k] = -1.0
        beq[k] = float(risk_net[k] - q0[step])
        row = n + k
        aeq[row, oe + k] = -1.0
        aeq[row, oe + k + 1] = 1.0
        aeq[row, oc + k] = -core.ETA_CHARGE
        aeq[row, od + k] = 1.0 / core.ETA_DISCHARGE

    aub = None
    bub = None
    if use_pwl:
        grid, values = terminal_curve
        slopes = np.diff(values) / np.diff(grid)
        intercepts = values[:-1] - slopes * grid[:-1]
        aub = sparse.lil_matrix((len(slopes), nvar))
        bub = np.zeros(len(slopes))
        for k, (slope, intercept) in enumerate(zip(slopes, intercepts)):
            aub[k, oe + n] = float(slope)
            aub[k, oz] = -1.0
            bub[k] = -float(intercept)

    bounds: List[Tuple[Optional[float], Optional[float]]] = []
    for step in steps:
        bounds.append((0.0, None) if block[0] <= step < block[1] else (0.0, 0.0))
    for step in steps:
        can_reduce = settlement == "B" and block[0] <= step < block[1]
        bounds.append((0.0, float(q0[step])) if can_reduce else (0.0, 0.0))
    bounds.extend([(0.0, core.STEP_LIMIT_KWH)] * n)
    bounds.extend([(0.0, core.STEP_LIMIT_KWH)] * n)
    bounds.extend([(0.0, None)] * n)
    bounds.extend([(0.0, None)] * n)
    bounds.extend([(core.SOC_MIN_KWH, core.SOC_MAX_KWH)] * (n + 1))
    if use_pwl:
        bounds.append((0.0, None))
    bounds[oe] = (start_soc, start_soc)
    if hard_anchor is not None:
        bounds[oe + n] = (hard_anchor, hard_anchor)

    started = time.perf_counter()
    result = linprog(
        obj,
        A_ub=None if aub is None else aub.tocsr(),
        b_ub=bub,
        A_eq=aeq.tocsr(),
        b_eq=beq,
        bounds=bounds,
        method="highs",
        options={"time_limit": 5.0},
    )
    elapsed = time.perf_counter() - started
    if not result.success:
        if settlement == "A" and result.status == 1:
            # Exact feasible fallback for the sensitivity model: retain q0.
            # This does not affect the B main result and is explicitly counted.
            return {
                "candidate": q0.copy(),
                "u": np.zeros(n),
                "r": np.zeros(n),
                "charge": np.zeros(n),
                "discharge": np.zeros(n),
                "planned_emergency": np.zeros(n),
                "soc": np.full(n + 1, start_soc),
                "max_residual": 0.0,
                "solve_seconds": float(elapsed),
                "fallback_keep_contract": True,
            }
        raise RuntimeError(f"调整LP失败 day={forecast.day_index} release={forecast.release_hour}: {result.message}")
    x = np.asarray(result.x)
    u, r = x[ou:ou + n], x[or_:or_ + n]
    candidate = q0.copy()
    candidate[steps] = q0[steps] + u - r
    eq_res = np.asarray(aeq.tocsr() @ x - beq)
    ub_res = np.asarray([0.0]) if aub is None else np.maximum(np.asarray(aub.tocsr() @ x - bub), 0.0)
    return {
        "candidate": candidate,
        "u": u,
        "r": r,
        "charge": x[oc:oc + n],
        "discharge": x[od:od + n],
        "planned_emergency": x[oh:oh + n],
        "soc": x[oe:oe + n + 1],
        "max_residual": float(max(np.abs(eq_res).max(), ub_res.max())),
        "solve_seconds": float(elapsed),
        "fallback_keep_contract": False,
    }


def block_score(
    q: np.ndarray,
    q0: np.ndarray,
    block: Tuple[int, int],
    start_soc: float,
    forecast_net: np.ndarray,
    scenarios: np.ndarray,
    price: np.ndarray,
    settlement: str,
) -> float:
    start, end = block
    u = np.maximum(q[start:end] - q0[start:end], 0.0)
    r = np.maximum(q0[start:end] - q[start:end], 0.0)
    sign = -0.5 if settlement == "B" else 0.5
    ordinary = float(np.sum(price[start:end] * q0[start:end] + 1.5 * price[start:end] * u + sign * price[start:end] * r))
    samples = scenarios if len(scenarios) else np.zeros((1, end - start))
    lam = core.ETA_DISCHARGE * float(np.median(price))
    scores = []
    for residual in samples:
        soc = float(start_soc)
        emergency_cost = 0.0
        for local, step in enumerate(range(start, end)):
            net = float(forecast_net[local] + residual[local])
            action = core.feedback_step(soc, float(q[step]), max(net, 0.0), max(-net, 0.0))
            soc = float(action["soc_after_kwh"])
            emergency_cost += 5.0 * price[step] * action["emergency_kwh"]
        scores.append(ordinary + emergency_cost - lam * soc)
    return float(np.mean(scores))


