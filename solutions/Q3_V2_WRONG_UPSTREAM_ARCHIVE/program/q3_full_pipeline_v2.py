def select_config(
    dataset: core.Dataset,
    cache: ForecastCache,
    curves: CurveCache,
) -> Tuple[Config, pd.DataFrame]:
    rows = []
    for correction in CORRECTIONS:
        for alpha in ALPHAS:
            cfg = Config(alpha, correction)
            log, decisions, _ = simulate_schedule(
                dataset, cache, curves, cfg, "M3", 0, 29,
                warm=None, settlement="B", progress=False,
            )
            metrics = summarize(log, 0, 29, dataset)
            asset_cost = metrics["total_cash_B_yuan"] - core.ETA_DISCHARGE * float(np.median(dataset.price)) * metrics["end_soc_kwh"]
            rows.append({
                "alpha": alpha,
                "load_correction": correction,
                "asset_adjusted_cost_yuan": asset_cost,
                "accepted_updates": int(decisions["accepted"].sum()) if len(decisions) else 0,
                **metrics,
            })
            print(f"SELECT {cfg.name} score={asset_cost:.6f}", flush=True)
    table = pd.DataFrame(rows).sort_values(
        ["asset_adjusted_cost_yuan", "emergency_kwh", "alpha", "load_correction"],
        kind="stable",
    ).reset_index(drop=True)
    best = table.iloc[0]
    return Config(float(best["alpha"]), bool(best["load_correction"])), table


def daily_metrics(log: pd.DataFrame) -> pd.DataFrame:
    frame = log.copy()
    frame["asset_adjusted_cost_B_yuan"] = (
        frame["ordinary_cost_B_yuan"] + frame["emergency_cost_yuan"]
    )
    grouped = frame.groupby("plan_day", as_index=False).agg(
        total_cash_B_yuan=("asset_adjusted_cost_B_yuan", "sum"),
        ordinary_cost_B_yuan=("ordinary_cost_B_yuan", "sum"),
        emergency_cost_yuan=("emergency_cost_yuan", "sum"),
        emergency_kwh=("actual_emergency_kwh", "sum"),
        unused_supply_kwh=("unused_supply_kwh", "sum"),
        qfinal_kwh=("qfinal_kwh", "sum"),
        start_soc_kwh=("soc_before_kwh", "first"),
        end_soc_kwh=("soc_after_kwh", "last"),
    )
    lam = core.ETA_DISCHARGE * float(np.median(log["price_yuan_per_kwh"]))
    grouped["asset_adjusted_cost_B_yuan"] = grouped["total_cash_B_yuan"] - lam * (
        grouped["end_soc_kwh"] - grouped["start_soc_kwh"]
    )
    return grouped


def block_bootstrap(diff: np.ndarray, block: int = 7) -> Dict[str, float]:
    rng = np.random.default_rng(BOOTSTRAP_SEED + block)
    n = len(diff)
    starts = np.arange(max(1, n - block + 1))
    means = np.empty(BOOTSTRAP_REPS)
    count = int(np.ceil(n / block))
    for i in range(BOOTSTRAP_REPS):
        sample = np.concatenate([diff[s:s + block] for s in rng.choice(starts, size=count, replace=True)])[:n]
        means[i] = float(np.mean(sample))
    return {
        "mean_daily_saving_yuan": float(np.mean(diff)),
        "ci95_low_yuan_per_day": float(np.quantile(means, 0.025)),
        "ci95_high_yuan_per_day": float(np.quantile(means, 0.975)),
        "block_days": block,
        "reps": BOOTSTRAP_REPS,
    }


def window(log: pd.DataFrame, start: pd.Timestamp, end: pd.Timestamp) -> pd.DataFrame:
    return log.loc[(log["interval_start"] >= start) & (log["interval_start"] < end)].copy()


def emergency_events(frame: pd.DataFrame) -> pd.DataFrame:
    tmp = frame.rename(columns={"actual_emergency_kwh": "emergency_grid_kwh"})
    raw = core.merge_emergency_events(tmp)
    if raw.empty:
        return pd.DataFrame(columns=["date", "start", "end", "time_period", "emergency_kwh", "duration_minutes"])
    raw["date"] = pd.to_datetime(raw["start"]).dt.normalize()
    raw["time_period"] = [
        core.format_event_time(pd.Timestamp(s), pd.Timestamp(e))
        for s, e in zip(raw["start"], raw["end"])
    ]
    raw["duration_minutes"] = (
        pd.to_datetime(raw["end"]) - pd.to_datetime(raw["start"])
    ).dt.total_seconds() / 60.0
    return raw[["date", "start", "end", "time_period", "emergency_kwh", "duration_minutes"]]


def natural_blocks(frame: pd.DataFrame, days: pd.DatetimeIndex) -> pd.DataFrame:
    parts = []
    labels = ("0:00-4:00", "4:00-8:00", "8:00-12:00", "12:00-16:00", "16:00-20:00", "20:00-24:00")
    for day in days:
        one = window(frame, day, day + pd.Timedelta(days=1)).sort_values("interval_start")
        if len(one) != 144:
            raise AssertionError(f"自然日不完整: {day.date()} {len(one)}")
        for block, label in enumerate(labels):
            part = one.iloc[block * 24:(block + 1) * 24]
            parts.append({
                "natural_day": day,
                "block": label,
                "charge_kwh": float(part["charge_kwh"].sum()),
                "discharge_kwh": float(part["discharge_kwh"].sum()),
                "interval_count": len(part),
            })
    return pd.DataFrame(parts)


