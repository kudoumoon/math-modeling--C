def audit_strategy(
    dataset: core.Dataset,
    log: pd.DataFrame,
    decisions: pd.DataFrame,
    plans: Dict[int, PlanRecord],
    schedule: str,
) -> Dict[str, object]:
    wp_start = dataset.dates[FIRST_DAY] + pd.Timedelta(minutes=10)
    wp_end = dataset.dates[LAST_DAY] + pd.Timedelta(days=1, minutes=10)
    wp = window(log, wp_start, wp_end)
    balance = (
        log["qfinal_kwh"] + log["pv_actual_kwh"] + log["discharge_kwh"]
        + log["actual_emergency_kwh"] - log["load_actual_kwh"]
        - log["charge_kwh"] - log["unused_supply_kwh"]
    ).to_numpy(float)
    state = (
        log["soc_after_kwh"] - log["soc_before_kwh"]
        - core.ETA_CHARGE * log["charge_kwh"]
        + log["discharge_kwh"] / core.ETA_DISCHARGE
    ).to_numpy(float)
    starts = pd.DatetimeIndex(log["interval_start"])
    ends = pd.DatetimeIndex(log["interval_end"])
    continuity = float(np.max(np.abs(
        log["soc_before_kwh"].to_numpy(float)[1:]
        - log["soc_after_kwh"].to_numpy(float)[:-1]
    )))
    arrays_independent = all(
        not np.shares_memory(plan.q0, plan.qfinal)
        for plan in plans.values()
    )
    one_confirmation = all(plan.confirmation_count.max() <= 1 for plan in plans.values())
    frozen_early = all(np.allclose(plan.q0[:35], plan.qfinal[:35]) for plan in plans.values())
    expected_decisions = len(plans) * len(RELEASE_SETS[schedule])
    history_causal = True
    pools_disjoint = True
    if len(decisions):
        history_causal = bool(all(
            (pd.isna(r.load_source_max) or pd.Timestamp(r.load_source_max) <= pd.Timestamp(r.issue_time))
            and (pd.isna(r.load_correction_source_max) or pd.Timestamp(r.load_correction_source_max) <= pd.Timestamp(r.issue_time))
            and (pd.isna(r.risk_day_last) or dataset.interval_starts(int(np.flatnonzero(dataset.dates == pd.Timestamp(r.risk_day_last))[0]))[143] + pd.Timedelta(minutes=10) <= pd.Timestamp(r.issue_time))
            for r in decisions.itertuples()
        ))
        pools_disjoint = bool(all(
            pd.isna(r.gate_day_last) or pd.isna(r.risk_day_first)
            or pd.Timestamp(r.gate_day_last) < pd.Timestamp(r.risk_day_first)
            for r in decisions.itertuples()
        ))
    expected_base = log["price_yuan_per_kwh"] * log["q0_kwh"]
    u = np.maximum(log["qfinal_kwh"] - log["q0_kwh"], 0.0)
    r = np.maximum(log["q0_kwh"] - log["qfinal_kwh"], 0.0)
    ledger_error = max(
        float(np.max(np.abs(log["base_plan_cost_yuan"] - expected_base))),
        float(np.max(np.abs(log["up_adjustment_cost_yuan"] - 1.5 * log["price_yuan_per_kwh"] * u))),
        float(np.max(np.abs(log["down_refund_B_yuan"] + 0.5 * log["price_yuan_per_kwh"] * r))),
    )
    scale = max(1.0, float(log[["qfinal_kwh", "load_actual_kwh", "pv_actual_kwh"]].to_numpy().max()))
    checks = {
        "01_wp_334x144": len(wp) == 334 * 144,
        "02_all_intervals_10min": bool(np.all((ends - starts).total_seconds() == 600.0)),
        "03_no_duplicate_or_gap": bool(not starts.duplicated().any() and np.all(starts[1:].asi8 == ends[:-1].asi8)),
        "04_energy_balance": bool(np.max(np.abs(balance)) <= TOL),
        "05_soc_balance": bool(np.max(np.abs(state)) <= TOL),
        "06_normalized_residual": bool(max(np.max(np.abs(balance)), np.max(np.abs(state))) / scale <= 1e-8),
        "07_soc_bounds": bool(log["soc_before_kwh"].min() >= core.SOC_MIN_KWH - TOL and log["soc_after_kwh"].max() <= core.SOC_MAX_KWH + TOL),
        "08_power_bounds": bool(log[["charge_kwh", "discharge_kwh"]].to_numpy().max() <= core.STEP_LIMIT_KWH + TOL),
        "09_actual_mutex": bool(not ((log["charge_kwh"] > TOL) & (log["discharge_kwh"] > TOL)).any()),
        "10_arrays_separate": arrays_independent,
        "11_one_confirmation": one_confirmation,
        "12_early_block_frozen": frozen_early,
        "13_decision_count": len(decisions) == expected_decisions,
        "14_sources_causal": history_causal,
        "15_risk_gate_disjoint": pools_disjoint,
        "16_adjustment_lp_residual": bool(len(decisions) == 0 or (decisions["lp_residual_kwh"] <= TOL).all()),
        "17_planned_mutex": bool(len(decisions) == 0 or (decisions["planned_mutex_violations"] == 0).all()),
        "18_q0_lp_residual": bool(max(p.q0_lp_residual for p in plans.values()) <= TOL),
        "19_ledger_identity": ledger_error <= TOL,
        "20_emergency_never_charges": bool(not ((log["actual_emergency_kwh"] > TOL) & (log["charge_kwh"] > TOL)).any()),
        "21_continuous_soc": continuity <= TOL,
        "22_nonnegative_contracts": bool(log[["q0_kwh", "qfinal_kwh", "actual_emergency_kwh"]].to_numpy().min() >= -TOL),
    }
    return {
        "status": "PASS" if all(checks.values()) else "FAIL",
        "checks": checks,
        "metrics": {
            "max_energy_residual_kwh": float(np.max(np.abs(balance))),
            "max_soc_residual_kwh": float(np.max(np.abs(state))),
            "normalized_residual": float(max(np.max(np.abs(balance)), np.max(np.abs(state))) / scale),
            "soc_continuity_error_kwh": continuity,
            "ledger_max_error_yuan": ledger_error,
            "q0_lp_p95_seconds": float(np.quantile([p.q0_solve_seconds for p in plans.values()], 0.95)),
            "update_lp_p95_seconds": float(np.quantile(decisions["solve_seconds"], 0.95)) if len(decisions) else 0.0,
        },
    }


def release_time_price_revaluation(
    plans: Dict[int, PlanRecord], dataset: core.Dataset, emergency_cost: float
) -> Dict[str, float]:
    base = up = refund = 0.0
    for plan in plans.values():
        base += float(np.dot(dataset.price, plan.q0))
        for release, (start, end) in q3p1.BLOCKS.items():
            p_release = float(dataset.price[start])
            u = np.maximum(plan.qfinal[start:end] - plan.q0[start:end], 0.0)
            r = np.maximum(plan.q0[start:end] - plan.qfinal[start:end], 0.0)
            up += 1.5 * p_release * float(u.sum())
            refund += -0.5 * p_release * float(r.sum())
    return {
        "base_plan_cost_yuan": base,
        "up_adjustment_cost_yuan": up,
        "down_refund_B_yuan": refund,
        "emergency_cost_yuan": emergency_cost,
        "total_cash_yuan": base + up + refund + emergency_cost,
    }


def run_full(skip_selection: bool = False) -> Dict[str, object]:
    OUT.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    dataset = core.load_dataset()
    book = q3p1.load_forecast_book(dataset)
    combo = (q3p1.LOAD_MODEL, q3p1.PV_MODEL_FOR_Q2_VALUE)
    q2_library = q2full.build_forecast_library(dataset, [combo])
    forecast_cache = ForecastCache(dataset, book, q2_library)
    curve_cache = CurveCache(dataset, q2_library)

    if skip_selection:
        selected = Config(0.65, True)
        selection = pd.DataFrame([{"alpha": 0.65, "load_correction": True, "note": "debug_skip_selection"}])
    else:
        selected, selection = select_config(dataset, forecast_cache, curve_cache)
    selection.to_csv(OUT / "q3_january_selection.csv", index=False, encoding="utf-8-sig")
    print(f"SELECTED alpha={selected.alpha} correction={selected.load_correction}", flush=True)

    warm = q2_warm_context(dataset)
    logs: Dict[str, pd.DataFrame] = {}
    decision_sets: Dict[str, pd.DataFrame] = {}
    plan_sets: Dict[str, Dict[int, PlanRecord]] = {}
    summaries: Dict[str, Dict[str, float]] = {}
    audits: Dict[str, Dict[str, object]] = {}
    for schedule in ("M0", "M1", "M2", "M3"):
        log, decisions, plans = simulate_schedule(
            dataset, forecast_cache, curve_cache, selected, schedule,
            FIRST_DAY, LAST_DAY, warm=warm, settlement="B", progress=True,
        )
        logs[schedule], decision_sets[schedule], plan_sets[schedule] = log, decisions, plans
        summaries[schedule] = summarize(log, FIRST_DAY, LAST_DAY, dataset)
        audits[schedule] = audit_strategy(dataset, log, decisions, plans, schedule)
        log.to_csv(OUT / f"q3_{schedule}_execution_log.csv", index=False, encoding="utf-8-sig")
        decisions.to_csv(OUT / f"q3_{schedule}_decisions.csv", index=False, encoding="utf-8-sig")
        print(f"DONE {schedule} cash={summaries[schedule]['total_cash_B_yuan']:.6f} audit={audits[schedule]['status']}", flush=True)

    official_start = dataset.dates[FIRST_DAY] + pd.Timedelta(minutes=10)
    official_end = dataset.dates[LAST_DAY] + pd.Timedelta(days=1, minutes=10)
    daily: Dict[str, pd.DataFrame] = {}
    for name, log in logs.items():
        daily[name] = daily_metrics(window(log, official_start, official_end))
        daily[name]["schedule"] = name
    pd.concat(daily.values(), ignore_index=True).to_csv(
        OUT / "q3_daily_schedule_comparison.csv", index=False, encoding="utf-8-sig"
    )

    lam = core.ETA_DISCHARGE * float(np.median(dataset.price))
    m0_asset = summaries["M0"]["total_cash_B_yuan"] - lam * (
        summaries["M0"]["end_soc_kwh"] - summaries["M0"]["start_soc_kwh"]
    )
    gates: Dict[str, Dict[str, object]] = {}
    for name in ("M1", "M2", "M3"):
        asset = summaries[name]["total_cash_B_yuan"] - lam * (
            summaries[name]["end_soc_kwh"] - summaries[name]["start_soc_kwh"]
        )
        saving = m0_asset - asset
        relative = saving / abs(m0_asset)
        merged = daily["M0"][["plan_day", "asset_adjusted_cost_B_yuan"]].merge(
            daily[name][["plan_day", "asset_adjusted_cost_B_yuan"]],
            on="plan_day", suffixes=("_M0", f"_{name}"), validate="one_to_one",
        )
        diff = merged["asset_adjusted_cost_B_yuan_M0"].to_numpy() - merged[f"asset_adjusted_cost_B_yuan_{name}"].to_numpy()
        boot = block_bootstrap(diff, 7)
        passed = bool(
            audits[name]["status"] == "PASS"
            and relative >= MIN_REL_SAVING
            and boot["ci95_low_yuan_per_day"] > 0.0
            and audits[name]["metrics"]["update_lp_p95_seconds"] < 5.0
        )
        gates[name] = {
            "asset_adjusted_saving_yuan": float(saving),
            "relative_asset_adjusted_saving": float(relative),
            "bootstrap_7day": boot,
            "update_lp_p95_seconds": audits[name]["metrics"]["update_lp_p95_seconds"],
            "passed": passed,
        }
    accepted = next((name for name in ("M3", "M2", "M1") if gates[name]["passed"]), "M0")
    print(f"ACCEPTED {accepted}", flush=True)

    accepted_log = logs[accepted]
    accepted_plans = plan_sets[accepted]
    natural = window(
        accepted_log,
        dataset.dates[FIRST_DAY],
        dataset.dates[LAST_DAY] + pd.Timedelta(days=1),
    )
    blocks = natural_blocks(natural, dataset.dates[FIRST_DAY:LAST_DAY + 1])
    events_wc = emergency_events(natural)
    events_wp = emergency_events(window(accepted_log, official_start, official_end))
    workbook, readback = write_result3(dataset, accepted_plans, accepted_log, blocks, events_wc)
    print("RESULT3_WRITTEN_AND_READ_BACK", flush=True)

    template_ok = bool(
        readback["sheet_names"] == ["计划购电量", "调整购电量", "充放电量", "紧急购电量"]
        and readback["plan_rows"] == 334
        and readback["adjust_rows"] == 334
        and readback["storage_rows"] == 334 * 6
        and readback["placeholder_count"] == 0
        and max(
            readback["plan_max_diff_kwh"], readback["adjust_max_diff_kwh"],
            readback["plan_amount_max_diff_kwh"], readback["adjust_amount_max_diff_kwh"],
            readback["plan_cost_max_diff_yuan"], readback["adjust_cost_max_diff_yuan"],
            readback["storage_charge_max_diff_kwh"], readback["storage_discharge_max_diff_kwh"],
        ) <= TOL
    )

    # A is both a post-hoc stress revaluation and an independently optimized
    # no-down-adjustment policy, as required by the ambiguity contract.
    if accepted == "M0":
        a_summary = summaries[accepted].copy()
        a_audit = audits[accepted]
    else:
        print("START_A_OPTIMIZED_SENSITIVITY", flush=True)
        a_log, a_decisions, a_plans = simulate_schedule(
            dataset, forecast_cache, curve_cache, selected, accepted,
            FIRST_DAY, LAST_DAY, warm=warm, settlement="A", progress=True,
        )
        a_summary = summarize(a_log, FIRST_DAY, LAST_DAY, dataset)
        a_audit = audit_strategy(dataset, a_log, a_decisions, a_plans, accepted)
        a_log.to_csv(OUT / "q3_A_optimized_execution_log.csv", index=False, encoding="utf-8-sig")
        a_decisions.to_csv(OUT / "q3_A_optimized_decisions.csv", index=False, encoding="utf-8-sig")

    transaction_price = release_time_price_revaluation(
        accepted_plans, dataset, summaries[accepted]["emergency_cost_yuan"]
    )
    repeated_adjustment = repeated_adjustment_ledger_sensitivity(
        accepted_plans, dataset.price, summaries[accepted]["total_cash_B_yuan"]
    )
    (OUT / "q3_repeated_adjustment_sensitivity.json").write_text(
        json.dumps(repeated_adjustment, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    oracle = q2full.solve_oracle(
        dataset,
        summaries[accepted]["start_soc_kwh"],
        summaries[accepted]["end_soc_kwh"],
    )

    comparison = pd.DataFrame([
        {"schedule": name, **summaries[name], "accepted_updates": int(decision_sets[name]["accepted"].sum()) if len(decision_sets[name]) else 0}
        for name in ("M0", "M1", "M2", "M3")
    ])
    comparison.to_csv(OUT / "q3_schedule_comparison.csv", index=False, encoding="utf-8-sig")
    monthly = []
    for name, frame in daily.items():
        f = frame.copy()
        f["month"] = pd.to_datetime(f["plan_day"]).dt.to_period("M").astype(str)
        g = f.groupby("month", as_index=False).agg(
            total_cash_B_yuan=("total_cash_B_yuan", "sum"),
            emergency_kwh=("emergency_kwh", "sum"),
            unused_supply_kwh=("unused_supply_kwh", "sum"),
        )
        g["schedule"] = name
        monthly.append(g)
    pd.concat(monthly, ignore_index=True).to_csv(
        OUT / "q3_monthly_information_value.csv", index=False, encoding="utf-8-sig"
    )
    focus_dates = pd.to_datetime(["2025-03-20", "2025-06-21", "2025-09-23", "2025-12-21"])
    window(accepted_log, official_start, official_end).loc[
        lambda x: pd.to_datetime(x["plan_day"]).isin(focus_dates)
    ].to_csv(OUT / "q3_focus_days.csv", index=False, encoding="utf-8-sig")
    blocks.to_csv(OUT / "q3_natural_day_blocks.csv", index=False, encoding="utf-8-sig")
    events_wc.to_csv(OUT / "q3_emergency_events_wc.csv", index=False, encoding="utf-8-sig")
    events_wp.to_csv(OUT / "q3_emergency_events_wp.csv", index=False, encoding="utf-8-sig")

    status = "PASS" if (
        all(a["status"] == "PASS" for a in audits.values())
        and a_audit["status"] == "PASS"
        and template_ok
        and Path(ROOT / "Q3" / "v2" / "result" / "p1" / "q3_p1_summary.json").exists()
    ) else "FAIL"
    result = {
        "status": status,
        "scope": "Q3 full 334-plan-day causal rolling backtest",
        "selected_parameters": {"alpha": selected.alpha, "load_correction": selected.load_correction},
        "accepted_schedule": accepted,
        "schedule_summaries": summaries,
        "upgrade_gates": gates,
        "audits": audits,
        "template_readback": readback,
        "template_ok": template_ok,
        "settlement_sensitivity": {
            "B_main_strategy_A_revaluation_total_yuan": summaries[accepted]["total_cash_A_revaluation_yuan"],
            "A_optimized": a_summary,
            "A_optimized_audit": a_audit,
            "release_time_price_B_revaluation": transaction_price,
            "repeated_adjustment_ledger": repeated_adjustment,
        },
        "perfect_foresight_physical_benchmark": oracle,
        "information_value": {
            "M1_minus_M0_cash_saving_yuan": summaries["M0"]["total_cash_B_yuan"] - summaries["M1"]["total_cash_B_yuan"],
            "M2_minus_M1_cash_saving_yuan": summaries["M1"]["total_cash_B_yuan"] - summaries["M2"]["total_cash_B_yuan"],
            "M3_minus_M2_cash_saving_yuan": summaries["M2"]["total_cash_B_yuan"] - summaries["M3"]["total_cash_B_yuan"],
        },
        "files": {
            "result3": str(workbook),
            "comparison": str(OUT / "q3_schedule_comparison.csv"),
            "daily": str(OUT / "q3_daily_schedule_comparison.csv"),
        },
        "manifest": {
            "inputs": {
                "attachment1": sha256(ROOT / "附件" / "附件1.xlsx"),
                "attachment2": sha256(ROOT / "附件" / "附件2.xlsx"),
                "attachment3": sha256(ROOT / "附件" / "附件3.xlsx"),
                "result3_template": sha256(TEMPLATE),
                "q2_execution_log": sha256(Q2_LOG),
                "analysis": sha256(ROOT / "题目分析报告.md"),
                "terms": sha256(ROOT / "术语表格.md"),
                "q3_p1_summary": sha256(ROOT / "Q3" / "v2" / "result" / "p1" / "q3_p1_summary.json"),
            },
            "code": sha256(Path(__file__)),
            "imported_q3_p1_code": sha256(PROGRAM_DIR / "q3_pipeline_v2.py"),
            "seed": BOOTSTRAP_SEED,
            "python": platform.python_version(),
            "numpy": np.__version__,
            "pandas": pd.__version__,
            "scipy": scipy.__version__,
            "openpyxl": openpyxl.__version__,
            "command": f'"{sys.executable}" Q3/v2/program/q3_full_pipeline_v2.py --mode full',
        },
        "runtime_seconds": time.perf_counter() - started,
    }
    (OUT / "q3_final_summary.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    if status != "PASS":
        raise AssertionError("Q3 full audit failed; inspect q3_final_summary.json")
    print(json.dumps({
        "status": status,
        "selected": result["selected_parameters"],
        "accepted_schedule": accepted,
        "accepted_summary": summaries[accepted],
        "upgrade_gates": gates,
        "runtime_seconds": result["runtime_seconds"],
    }, ensure_ascii=False, indent=2), flush=True)
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["full"], default="full")
    parser.add_argument("--skip-selection", action="store_true")
    args = parser.parse_args()
    run_full(skip_selection=args.skip_selection)


if __name__ == "__main__":
    main()
